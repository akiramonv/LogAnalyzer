package io.github.loganalyzer.core.model;

/** Тип события в таймлайне — определяет, как событие отображается и как трактуется анализатором. */
public enum EventKind {
    /** Обычная запись лога. */
    LOG,
    /** Запись с прикреплённым стек-трейсом (исключением). */
    EXCEPTION,
    /** Исходящий или входящий HTTP-запрос. */
    HTTP_REQUEST,
    /** HTTP-ответ. */
    HTTP_RESPONSE,
    /** Строка, которую не удалось отнести ни к одному формату (сохраняется как есть). */
    UNPARSED
}
